    expect(sqliteRebuildPlan.fullSql).toContain('__dbm_migrate_customers');
    expect(sqliteRebuildPlan.fullSql).toContain('SELECT "id", "full_name", "email", "tier", "is_active", "created_at" FROM "customers"');
    expect(sqliteRebuildPlan.fullSql).toContain('PRAGMA foreign_key_check;');

    // Safety blocker when dependent views or triggers exist on SQLite table
    const blockedDoc = structuredClone(editedSqlite);
    blockedDoc.tables[0].baselineSnapshot!.hasDependentViewsOrTriggers = true;
    const blockedPlan = buildSqlMigrationPlan(blockedDoc, { targetDialect: 'sqlite' });
    expect(blockedPlan.blockers.length).toBeGreaterThan(0);
    expect(blockedPlan.blockers[0]).toMatch(/viste o trigger/i);

