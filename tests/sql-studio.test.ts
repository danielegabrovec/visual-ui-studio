  it('4. compiles bidirectional Visual Query Graph <-> parameterized SQL across all 5 dialects', () => {
    const doc = createStarterSqlDocument('proj_q', 'QueryGraphTest', 'postgresql');
    const joinGraph = {
      kind: 'select' as const,
      sourceTable: 'orders',
      sourceAlias: 'o',
      selectedColumns: ['id', 'total_eur', 'status'],
      joins: [
        {
          id: 'j1',
          joinType: 'INNER' as const,
          table: 'customers',
          alias: 'c',
          leftColumn: 'customer_id',
          rightColumn: 'id',
        },
      ],
      filters: [
        {
          id: 'f1',
          column: 'status',
          operator: '=' as const,
          value: 'paid',
        },
      ],
      groupBy: [],
      aggregates: [],
      orderBy: [{ column: 'id', direction: 'DESC' as const }],
      limit: 25,
      offset: 10,
    };

    const pgOut = compileOperationGraphToSql(joinGraph, doc, 'postgresql');
    expect(pgOut.sql).toContain('INNER JOIN "public"."customers" AS "c" ON "o"."customer_id" = "c"."id"');
    expect(pgOut.sql).toContain('WHERE "o"."status" = $1');
    expect(pgOut.sql).toContain('LIMIT 25 OFFSET 10');

    const tsqlOut = compileOperationGraphToSql(joinGraph, doc, 'sqlserver');
    expect(tsqlOut.sql).toContain('WHERE [o].[status] = @status_1');
    expect(tsqlOut.sql).toContain('OFFSET 10 ROWS FETCH NEXT 25 ROWS ONLY');

    // Reverse-parse SQL back into OperationGraph
    const reversed = parseSqlToOperationGraph(
      'SELECT o.id, o.total_eur FROM orders AS o INNER JOIN customers AS c ON o.customer_id = c.id WHERE o.status = \'paid\' ORDER BY o.id DESC LIMIT 25 OFFSET 10;',
      doc,
      'sqlite',
    );
    expect(reversed.graph).not.toBeNull();
    expect(reversed.graph!.sourceTable).toBe('orders');
    expect(reversed.graph!.joins).toHaveLength(1);
    expect(reversed.graph!.joins[0].table).toBe('customers');
    expect(reversed.graph!.filters[0].column).toBe('status');
    expect(reversed.graph!.limit).toBe(25);
    expect(reversed.graph!.offset).toBe(10);
  });

  it('5. handles Excel-style grid editing, precision-safe >2^53 integers, RFC TSV/CSV paste, CTE/alias autocomplete & Italian query explanation', () => {
    const doc = createStarterSqlDocument('proj_grid', 'GridLang', 'sqlite');
    const ordersTbl = doc.tables[1];

    // Precision-safe integer > Number.MAX_SAFE_INTEGER stays exact string!
    const bigCol = { ...ordersTbl.columns[0], canonicalType: 'bigint' as const, nativeType: 'BIGINT' };
    const hugeInt = '9007199254740999123';
    expect(parseGridCellInput(hugeInt, bigCol)).toBe(hugeInt);
    expect(parseGridCellInput('1490.00', ordersTbl.columns[2])).toBe('1490.00');

    // TSV Paste with header auto-skip and unquoted \N = null vs quoted "NULL" = text
    const customersTbl = doc.tables[0];
    const baseRows = structuredClone(doc.seedRows[0].rows);
    const pkCols = ['id'];
    const allCols = customersTbl.columns.map((c) => c.name);

    const tsv = [
      'id\tfull_name\temail\ttier\tis_active\tcreated_at',
      '1\tGiulia Conti Aggiornata\tgiulia.conti@studio.it\tenterprise\t1\t2026-03-10 09:30:00',
      '\tLuca Neri\tluca.neri@studio.it\tpro\t1\t2026-03-15 12:00:00',
    ].join('\r\n');

    const pastePlan = buildClipboardPastePlan(
      baseRows,
      [],
      customersTbl.columns,
      { row: 0, column: 0 },
      tsv,
      pkCols,
    );
    expect(pastePlan.skippedHeader).toBe(true);
    expect(pastePlan.issues).toHaveLength(0);

    // Stage paste + new row + delete row
    let staged = stageCellEdit(baseRows, [], 0, 'full_name', 'Giulia Modificata', pkCols, allCols);
    staged = stageNewBlankRow(staged, customersTbl.columns);
    staged = stageDeleteOrRestoreRow(baseRows, staged, 1, pkCols, allCols);

    const mat = materializeGridRows(baseRows, staged, pkCols, allCols);
    expect(mat[0].status).toBe('updated');
    expect(mat[1].status).toBe('deleted');
    expect(mat[mat.length - 1].status).toBe('inserted');

    // Also verify multi-row append paste plan applies cleanly
    const appendPlan = buildClipboardPastePlan(
      baseRows,
      [],
      customersTbl.columns,
      { row: baseRows.length, column: 0 },
      '\tAnna Blu\tanna@blu.it\tstandard\t1\t2026-03-16 08:00:00',
      pkCols,
    );
    const afterAppend = applyPastePlanToStagedChanges(baseRows, [], appendPlan, pkCols, allCols);
    expect(afterAppend).toHaveLength(1);
    expect(afterAppend[0].kind).toBe('insert');

    // CTE & Alias-aware SQL Autocomplete + Italian Explanation
    const cteSql =
      'WITH vip AS (SELECT id, email FROM customers WHERE tier = \'enterprise\') SELECT v. FROM vip v;';
    const cursorAfterDot = cteSql.indexOf('v.') + 2;
    const completions = getSqlCompletions({
      sql: cteSql,
      cursorOffset: cursorAfterDot,
      dialect: 'postgresql',
      schema: doc,
    });
    expect(completions.map((c) => c.label)).toContain('email');

    const dangerousSql = 'DELETE FROM orders;';
    const explained = explainSqlInItalian(dangerousSql, 'sqlite', doc);
    expect(explained.warnings.some((w) => w.includes('WHERE'))).toBe(true);
    expect(splitSqlStatements('SELECT 1; -- comment ;\nSELECT \';\' AS semi;', 'sqlite')).toHaveLength(2);
  });

  it('6. synthesizes Canvas CRUD UI with parameterized create, update, delete and lossless Undo', async () => {
    const sqlDoc = createStarterSqlDocument('proj_ui', 'UiBridgeApp', 'postgresql');
    const demoSheet = createStarterDemoSheet('proj_ui', 'sheet_main', 'MainScreen');
    const ordersTable = sqlDoc.tables[1]; // has FK `customer_id -> customers.id` AND `CHECK (status IN (...))`

    const bridgeOut = synthesizeCrudUiFromSqlTable({
      table: ordersTable,
      sqlDocument: sqlDoc,
      sheet: demoSheet,
      scriptLanguage: 'typescript',
    });

    // Check FK `customer_id` mapped to `select` with customer names from seedRows
    const custField = bridgeOut.fields.find((f) => f.column.name === 'customer_id')!;
    expect(custField.controlType).toBe('select');
    expect(custField.options?.some((o) => o.includes('Giulia Conti'))).toBe(true);

    // Check `status` CHECK IN ('pending', 'paid', 'shipped', 'cancelled') mapped to `select`
    const statusField = bridgeOut.fields.find((f) => f.column.name === 'status')!;
    expect(statusField.controlType).toBe('select');
    expect(statusField.options).toEqual(['pending', 'paid', 'shipped', 'cancelled']);

    expect(bridgeOut.automations).toHaveLength(5);
    expect(bridgeOut.namedQueries).toHaveLength(5);
    const update = bridgeOut.automations.flatMap((automation) => automation.steps).find((step) =>
      step.kind === 'sql_operation' && step.operation === 'update_by_id');
    expect(update).toMatchObject({
      namedQueryId: 'qry_update_orders',
      refreshQueryId: 'qry_list_orders',
      paramBindings: { id: { source: 'ui_element', prop: 'value' } },
    });
    const { project } = await dbService.createProject({ name: 'Generated CRUD' });
    const searchQuery = bridgeOut.namedQueries.find((query) => query.name === 'search_orders')!;
    const found = await dbService.executeSqlQuery({
      projectId: project.id, sandboxMode: true, dialect: 'postgresql', sql: searchQuery.canonicalSql, parameters: ['PAID'],
    });
    expect(found.rows.map((row) => row.id)).toEqual([101]);
    const insertQuery = bridgeOut.namedQueries.find((query) => query.kind === 'insert')!;
    expect(insertQuery.parameters.map((parameter) => parameter.name)).toEqual(bridgeOut.fields.map((field) => field.column.name));
    const updateQuery = bridgeOut.namedQueries.find((query) => query.kind === 'update')!;
    const changed = await dbService.executeSqlQuery({
      projectId: project.id, sandboxMode: true, dialect: 'postgresql', sql: updateQuery.canonicalSql,
      parameters: updateQuery.parameters.map((parameter) => ({ id: 101, customer_id: 1, total_eur: '12.50', status: 'shipped' })[parameter.name] ?? null),
    });
    expect(changed).toMatchObject({ ok: true, affectedRows: 1 });
    const refreshed = await dbService.executeSqlQuery({ projectId: project.id, sql: 'SELECT status FROM orders WHERE id = 101' });
    expect(refreshed.rows).toEqual([{ status: 'shipped' }]);

    // Apply UIPatchOps to Canvas sheet and verify lossless Undo!
    const beforeNodeCount = Object.keys(demoSheet.nodes).length;
    const { nextSheet, inverseOps } = applyPatchOpsToSheet(demoSheet, bridgeOut.ops);
    expect(Object.keys(nextSheet.nodes).length).toBeGreaterThan(beforeNodeCount + 6);
    expect(nextSheet.nodes[bridgeOut.rootCardNodeId]).toBeDefined();
    expect(nextSheet.nodes[bridgeOut.tableNodeId!]?.content?.controlType).toBe('table');

    const { nextSheet: undoneSheet } = applyPatchOpsToSheet(nextSheet, inverseOps);
    expect(Object.keys(undoneSheet.nodes).length).toBe(beforeNodeCount);
  });

