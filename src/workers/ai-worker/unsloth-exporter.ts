import { mkdir, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import type {
  ExportUnslothDatasetRequest,
  ExportUnslothDatasetResult,
  UnslothTrainingPairDTO,
} from '@shared/ipc-contract';

const SYSTEM_PROMPT_FOR_TRAINING =
  'You are a specialized UI Architecture & Multi-Target Codegen model trained with Visual UI Studio. Given a user UI prompt, Design Tokens, and normalized UI-IR SceneGraph JSON, emit clean, accessible, idiomatic target framework code.';

function formatShareGptLine(pair: UnslothTrainingPairDTO): string {
  const humanParts = [
    `Target Framework: ${pair.targetFramework}`,
    `Task: ${pair.promptSummary}`,
    `UI-IR SceneGraph JSON:\n${pair.normalizedUiIrJson}`,
  ];
  if (pair.tokensSnapshotJson) {
    humanParts.push(`Design Tokens JSON:\n${pair.tokensSnapshotJson}`);
  }

  return JSON.stringify({
    conversations: [
      { from: 'system', value: SYSTEM_PROMPT_FOR_TRAINING },
      { from: 'human', value: humanParts.join('\n\n') },
      { from: 'gpt', value: pair.acceptedCodeOutput },
    ],
    metadata: {
      pair_id: pair.id,
      target_framework: pair.targetFramework,
      quality_score: pair.qualityScore,
    },
  });
}

function formatAlpacaLine(pair: UnslothTrainingPairDTO): string {
  const inputContext = pair.tokensSnapshotJson
    ? `UI-IR:\n${pair.normalizedUiIrJson}\n\nTokens:\n${pair.tokensSnapshotJson}`
    : `UI-IR:\n${pair.normalizedUiIrJson}`;

  return JSON.stringify({
    instruction: `[Target: ${pair.targetFramework}] ${pair.promptSummary}`,
    input: inputContext,
    output: pair.acceptedCodeOutput,
  });
}

function generateUnslothTrainingPythonScript(
  datasetFileName: string,
  format: 'sharegpt' | 'alpaca',
  baseModelRepo: string,
): string {
  return `#!/usr/bin/env python3
"""
Auto-generated by Visual UI Studio — Unsloth QLoRA + Dynamic GGUF Fine-Tuning Script
Trains a custom local UI-to-Code LLM on your SQLite-exported Canvas-to-Code pairs
and exports a ready-to-run GGUF for Ollama / LM Studio!

Install requirements (Linux / WSL2 / Colab):
  pip install "unsloth[colab-new] @ git+https://github.com/unslothai/unsloth.git"
  pip install --no-deps trl peft accelerate bitsandbytes datasets
"""

from datasets import load_dataset
from trl import SFTTrainer
from transformers import TrainingArguments
from unsloth import FastLanguageModel, is_bfloat16_supported

BASE_MODEL = ${JSON.stringify(baseModelRepo)}
DATASET_FILE = ${JSON.stringify(datasetFileName)}
DATASET_FORMAT = ${JSON.stringify(format)}
MAX_SEQ_LENGTH = 8192
OUTPUT_GGUF_DIR = "ui_studio_custom_gguf"

def main() -> None:
    model, tokenizer = FastLanguageModel.from_pretrained(
        model_name=BASE_MODEL,
        max_seq_length=MAX_SEQ_LENGTH,
        dtype=None,
        load_in_4bit=True,
    )

    model = FastLanguageModel.get_peft_model(
        model,
        r=16,
        target_modules=["q_proj", "k_proj", "v_proj", "o_proj", "gate_proj", "up_proj", "down_proj"],
        lora_alpha=16,
        lora_dropout=0,
        bias="none",
        use_gradient_checkpointing="unsloth",
        random_state=3407,
    )

    dataset = load_dataset("json", data_files=DATASET_FILE, split="train")

    def format_prompts(examples):
        texts = []
        if DATASET_FORMAT == "sharegpt":
            for conv in examples["conversations"]:
                rendered = "\\n".join([f"<|{turn['from']}|>\\n{turn['value']}" for turn in conv])
                texts.append(rendered + tokenizer.eos_token)
        else:
            for inst, inp, out in zip(examples["instruction"], examples["input"], examples["output"]):
                rendered = f"### Instruction:\\n{inst}\\n\\n### Input:\\n{inp}\\n\\n### Response:\\n{out}"
                texts.append(rendered + tokenizer.eos_token)
        return {"text": texts}

    dataset = dataset.map(format_prompts, batched=True)

    trainer = SFTTrainer(
        model=model,
        tokenizer=tokenizer,
        train_dataset=dataset,
        dataset_text_field="text",
        max_seq_length=MAX_SEQ_LENGTH,
        dataset_num_proc=2,
        args=TrainingArguments(
            per_device_train_batch_size=2,
            gradient_accumulation_steps=4,
            warmup_steps=5,
            max_steps=60,
            learning_rate=2e-4,
            fp16=not is_bfloat16_supported(),
            bf16=is_bfloat16_supported(),
            logging_steps=1,
            optim="adamw_8bit",
            weight_decay=0.01,
            lr_scheduler_type="linear",
            seed=3407,
            output_dir="outputs_lora",
        ),
    )

    trainer.train()

    # Export quantized GGUF ready for Ollama & LM Studio
    model.save_pretrained_gguf(
        OUTPUT_GGUF_DIR,
        tokenizer,
        quantization_method="q4_k_m",
    )
    print(f"Done! Import into Ollama via: ollama create ui-studio-custom -f Modelfile")

if __name__ == "__main__":
    main()
`;
}

function generateOllamaModelfile(): string {
  return `# Auto-generated Ollama Modelfile for Visual UI Studio Fine-Tuned Model
# Usage after running train_unsloth_lora.py:
#   ollama create ui-studio-custom -f Modelfile

FROM ./ui_studio_custom_gguf/unsloth.Q4_K_M.gguf

PARAMETER temperature 0.15
PARAMETER top_p 0.9
PARAMETER num_ctx 16384

SYSTEM """${SYSTEM_PROMPT_FOR_TRAINING}"""
`;
}

export async function writeUnslothExportBundle(input: {
  pairs: UnslothTrainingPairDTO[];
  request: ExportUnslothDatasetRequest;
  resolvedOutputDir: string;
}): Promise<ExportUnslothDatasetResult> {
  const { pairs, request, resolvedOutputDir } = input;
  await mkdir(resolvedOutputDir, { recursive: true });

  const format = request.format === 'alpaca' ? 'alpaca' : 'sharegpt';
  const baseModelRepo = request.baseModelRepo?.trim() || 'unsloth/Qwen2.5-Coder-7B-Instruct-bnb-4bit';
  const datasetFileName = `dataset_${format}.jsonl`;

  const datasetFilePath = join(resolvedOutputDir, datasetFileName);
  const trainScriptPath = join(resolvedOutputDir, 'train_unsloth_lora.py');
  const modelfilePath = join(resolvedOutputDir, 'Modelfile');

  const lines = pairs.map((pair) => (format === 'alpaca' ? formatAlpacaLine(pair) : formatShareGptLine(pair)));
  const jsonlBody = lines.length > 0 ? `${lines.join('\n')}\n` : '';

  await Promise.all([
    writeFile(datasetFilePath, jsonlBody, 'utf8'),
    writeFile(
      trainScriptPath,
      generateUnslothTrainingPythonScript(datasetFileName, format, baseModelRepo),
      'utf8',
    ),
    writeFile(modelfilePath, generateOllamaModelfile(), 'utf8'),
  ]);

  return {
    outputDir: resolvedOutputDir,
    datasetFilePath,
    trainScriptPath,
    modelfilePath,
    pairCount: pairs.length,
  };
}
